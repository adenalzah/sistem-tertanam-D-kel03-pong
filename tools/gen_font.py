FIRST, LAST = 0x20, 0x5F


def encode(rows):
    v = 0
    for r, row in enumerate(rows):
        assert len(row) == 3, rows
        for c, ch in enumerate(row):
            if ch == '#':
                v |= 1 << (r * 3 + (2 - c))
    return v


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "sw", "common", "font.h")
    lines = [
        "/* font.h -- DIBANGKITKAN OTOMATIS oleh tools/gen_font.py. Jangan disunting manual. */",
        "/* Glyph 3x5: bit (baris*3 + (2-kolom)) = 1 berarti piksel menyala. */",
        "#ifndef FONT_H",
        "#define FONT_H",
        "#include <stdint.h>",
        f"#define FONT_FIRST 0x{FIRST:02X}",
        f"#define FONT_LAST  0x{LAST:02X}",
        "static const uint16_t font3x5[FONT_LAST - FONT_FIRST + 1] = {",
    ]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = GLYPHS.get(ch, GLYPHS['?'])
        shown = ch if ch not in "\\" else "backslash"
        lines.append(f"    0x{encode(rows):04X}, /* '{shown}' */")
    lines += ["};", "#endif", ""]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("ditulis:", os.path.normpath(out))


if __name__ == "__main__":
    main()
